# Issue #208 task 2: AUPRC subset+weight search over deployable train-only members.
#
# Pool = published fp16 weights (weights-1016) AND train-only AND valid probs available.
# Objective: valid (5849) AUPRC maximised by probability-space weighted blending
# (deployable 1:1 via submit_pkg predict.py --blend). Forward greedy with coordinate
# descent re-optimisation (0.05 coarse / 0.01 fine) + exhaustive k<=3 cross-check.
# Hard size constraint: fp16 bytes sum <= 500,000,000 (decompressed, actually loaded).
#
# Prob-file resolution per member, first hit wins:
#   1) --pil-dir <member>_pil.npy        (npz: probs_tta4, PIL-direct pipeline,
#                                         single-scale TTA4 — the uniform regime)
#   2) --ens8-dir <ens8 fname>           (legacy multi-scale TTA for ConvNeXt members,
#                                         single-scale TTA4 for effnet/seed2; npys
#                                         generated by make_ens8.py on the cache512)
#   3) --assets-dir <assets fname>       (official release npy/CSV, TTA4 on cache)
# Each loaded member is tagged with its regime; --regime restricts the search to one
# regime so blends never mix metric definitions. Missing members are skipped with a
# warning and recorded in the output JSON.
#
# Usage:
#   python tools/finals_208_search.py \
#     --pil-dir .scratch_208 \
#     --ens8-dir D:/glaucoma_work/ens8_probs \
#     --assets-dir D:/glaucoma_work/finals_208_assets \
#     --csv-root glaucoma_first \
#     --regime pil4 \
#     --out docs/finals/candidates_208_search.json
import argparse, csv, itertools, json, os

import numpy as np
from sklearn.metrics import average_precision_score, roc_auc_score

BUDGET = 500_000_000

# member -> (ens8 prob filename, fp16 bytes, train scope)
MEMBERS_SPEC = {
    "cb512":    ("cb512_val.npy",    176_328_486, "train-only"),
    "hi512_v2": ("hi512_v2_val.npy",  99_843_809, "train-only"),
    "seed2":    ("seed2_val.npy",      99_844_892, "train-only"),
    "cb384":    ("cb384_val.npy",     176_328_125, "train-only"),
    "b448":     ("b448_val.npy",       23_544_137, "train-only"),
    "b384":     ("b384_val.npy",       23_547_284, "train-only"),
    "b512":     ("b512_val.npy",       23_544_137, "train-only"),
    "ctiny384": ("ctiny512_probs_valid_full_tta4.npy", 56_518_009, "train-only"),
}


def load_probs(path):
    if path.endswith(".npz"):
        z = np.load(path)
        return z["probs_tta4"].astype(np.float64), "pil4"
    arr = np.load(path).astype(np.float64)
    return arr, "legacy"


def opt_weights(probs_list, labels, iters=6, coarse=0.05, fine=0.01):
    k = len(probs_list)
    w = np.full(k, 1.0 / k)
    best = average_precision_score(labels, sum(p * x for p, x in zip(probs_list, w)))
    for step in (coarse, fine):
        for _ in range(iters):
            improved = False
            for i in range(k):
                for dw in np.arange(-1.0, 1.0 + 1e-9, step):
                    w2 = w.copy()
                    w2[i] += dw
                    if w2.min() < -1e-9:
                        continue
                    w2 = np.clip(w2, 0, None)
                    s = w2.sum()
                    if s <= 0:
                        continue
                    w2 = w2 / s
                    sc = average_precision_score(
                        labels, sum(p * x for p, x in zip(probs_list, w2)))
                    if sc > best + 1e-9:
                        best, w, improved = sc, w2, True
            if not improved:
                break
    return w, best


def main():
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    ap = argparse.ArgumentParser()
    ap.add_argument("--pil-dir", default=os.path.join(here, ".scratch_208"),
                    help="dir of <member>_pil.npy npz from the PIL-direct gate runs")
    ap.add_argument("--ens8-dir", default=r"D:\glaucoma_work\ens8_probs")
    ap.add_argument("--weights-dir", default=r"D:\glaucoma_work\weights")
    ap.add_argument("--assets-dir", default=r"D:\glaucoma_work\finals_208_assets")
    ap.add_argument("--csv-root", default=os.path.join(here, "glaucoma_first"))
    ap.add_argument("--regime", default="pil4", choices=["pil4", "legacy", "all"],
                    help="restrict search to one prob regime (all = mixed, warned)")
    ap.add_argument("--out", default=None, help="write results json here")
    args = ap.parse_args()

    with open(os.path.join(args.csv_root, "valid.csv"), encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    labels = np.array([int(r["True_Label"]) for r in rows])

    P, meta, missing = {}, {}, []
    for m, (fname, nbytes, scope) in MEMBERS_SPEC.items():
        p = os.path.join(args.pil_dir, f"{m}_pil.npy")
        if os.path.exists(p):
            P[m], reg = load_probs(p)
            meta[m] = {"bytes": nbytes, "scope": scope, "regime": reg, "path": p}
            continue
        for d in (args.ens8_dir, args.weights_dir, args.assets_dir):
            q = os.path.join(d, fname)
            if os.path.exists(q):
                P[m], reg = load_probs(q)
                meta[m] = {"bytes": nbytes, "scope": scope, "regime": reg, "path": q}
                break
        else:
            missing.append(m)
    if missing:
        print(f"WARNING: skipped, no prob file: {missing}")
    if not P:
        raise SystemExit("no member prob files found in any --*-dir")
    regs = sorted({meta[m]["regime"] for m in P})
    if len(regs) > 1 and args.regime == "all":
        print(f"WARNING: mixed regimes {regs}; blends compare different TTA definitions")

    pool = [m for m in P if args.regime == "all" or meta[m]["regime"] == args.regime]
    if not pool:
        raise SystemExit(f"no members in regime '{args.regime}'; available: {regs}")
    print(f"pool ({args.regime}): {pool}")

    def size(lst):
        return sum(meta[m]["bytes"] for m in lst)

    results = {"budget": BUDGET, "regime": args.regime,
               "missing": missing, "singles": [], "greedy": [],
               "exhaustive_k3": [], "notable": []}

    for m in pool:
        results["singles"].append({
            "member": m, "auprc": round(average_precision_score(labels, P[m]), 5),
            "auroc": round(roc_auc_score(labels, P[m]), 5), **meta[m]})

    # ens9 historical recipe as reference (only when fully in-pool)
    ens9 = ["cb512", "hi512_v2", "cb384", "b512"]
    if all(m in pool for m in ens9):
        w9 = [0.591, 0.224, 0.141, 0.044]
        p9 = sum(P[m] * x for m, x in zip(ens9, w9))
        results["ref_ens9_recipe"] = {"members": ens9, "weights": w9, "bytes": size(ens9),
                                      "auprc": round(average_precision_score(labels, p9), 5),
                                      "auroc": round(roc_auc_score(labels, p9), 5)}

    # forward greedy
    current = []
    for _ in range(6):
        best_step = None
        for m in pool:
            if m in current:
                continue
            trial = current + [m]
            if size(trial) > BUDGET:
                continue
            w, sc = opt_weights([P[x] for x in trial], labels)
            if best_step is None or sc > best_step[2]:
                best_step = (trial, w, sc)
        if best_step is None:
            break
        current, w, sc = best_step
        results["greedy"].append({"members": current, "weights": [round(float(x), 4) for x in w],
                                  "bytes": size(current), "auprc": round(sc, 5),
                                  "auroc": round(roc_auc_score(
                                      labels, sum(P[m] * x for m, x in zip(current, w))), 5)})

    # exhaustive k<=3
    subs = []
    for k in (1, 2, 3):
        for combo in itertools.combinations(pool, k):
            if size(list(combo)) > BUDGET:
                continue
            w, sc = opt_weights([P[x] for x in combo], labels)
            subs.append((sc, list(combo), w))
    subs.sort(reverse=True)
    for sc, combo, w in subs[:12]:
        results["exhaustive_k3"].append({"members": combo,
                                         "weights": [round(float(x), 4) for x in w],
                                         "bytes": size(combo), "auprc": round(sc, 5)})

    notable = [
        ["cb512", "hi512_v2", "b512"],
        ["cb512", "hi512_v2", "seed2", "b448"],
        ["cb512", "hi512_v2", "b512", "ctiny384", "seed2"],
        ["cb512", "hi512_v2", "seed2", "ctiny384", "b448"],
        ["cb512", "cb384", "hi512_v2", "b448"],
        ["cb512", "cb384", "hi512_v2"],
    ]
    for lst in notable:
        if not all(m in pool for m in lst):
            continue
        if size(lst) > BUDGET:
            results["notable"].append({"members": lst, "over_budget": True,
                                       "bytes": size(lst)})
            continue
        w, sc = opt_weights([P[x] for x in lst], labels)
        results["notable"].append({"members": lst,
                                   "weights": [round(float(x), 4) for x in w],
                                   "bytes": size(lst), "auprc": round(sc, 5)})

    print(json.dumps(results, indent=1))
    if args.out:
        os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
        with open(args.out, "w", encoding="utf-8") as f:
            json.dump(results, f, ensure_ascii=False, indent=1)


if __name__ == "__main__":
    main()
